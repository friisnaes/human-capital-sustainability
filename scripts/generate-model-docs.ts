/**
 * Genererer docs/MODELKATALOG.md fra den samme konfiguration og de samme
 * beregninger, som applikationen bruger. Kør: npm run docs:model
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { demoDataset } from '../src/data/demo';
import { DIMENSIONS, INDICATORS } from '../src/model/catalog';
import { CRITICALITY, CURRENT_MODEL, MIN_N, MODEL_VERSIONS, NORMALIZATION, RISK_MODEL, WINDOWS, type DimensionId } from '../src/model/config';
import { computeOrs, createAnalysis, DIMENSION_INDICATORS } from '../src/model/ors';
import { computeRisks, topDistinctRisks } from '../src/model/risk';
import { fmtNumber, fmtPct } from '../src/lib/format';

const D: DimensionId[] = ['D1', 'D2', 'D3', 'D4', 'D5', 'D6'];
const asOf = demoDataset.dataAsOf;
const a = createAnalysis(demoDataset, asOf);
const ors = computeOrs(a, null);
const top = topDistinctRisks(computeRisks(a), 3);
const L: string[] = [];
const p = (s = '') => L.push(s);

p('# Modelkatalog – Organizational Resilience Score™ og risikomodel');
p();
p(`> Genereret automatisk fra koden (\`npm run docs:model\`). ORS-model v${CURRENT_MODEL.version}, risikomodel v${RISK_MODEL.version}. Tallene i eksempel B stammer fra de fiktive demonstrationsdata pr. ${asOf.split('-').reverse().join('.')}.`);
p();
p('Modellen er en **forklarlig prototype til beslutningsstøtte**. Vægte, tærskler og normaliseringer er faglige antagelser, der skal kalibreres og valideres med virkelige data. Modellen påviser ikke årsagssammenhænge og bruger ingen branchebenchmarks.');
p();
p('## 1. Modelversioner');
p();
p('| Version | Gyldig fra | Ændring |');
p('|---|---|---|');
for (const m of MODEL_VERSIONS) p(`| ORS ${m.version} | ${m.validFrom} | ${m.changeNote} |`);
p(`| Risiko ${RISK_MODEL.version} | ${MODEL_VERSIONS[0]!.validFrom} | Prioritet ud fra konsekvens, eksponering og beredskab; sandsynlighed vises separat. |`);
p();
p('Historik vises både som *rapporteret* (med den model, der var gældende i perioden) og *genberegnet* (med den gældende model).');
p();
p('## 2. Principper');
p();
p(`- Manglende data bliver aldrig til nul. Observationer uden data udelades og trækker datadækningen ned.`);
p(`- En dimension vises kun ved datadækning ≥ ${fmtPct(CURRENT_MODEL.minDimensionCoverage)}. ORS vises kun, når dimensioner med score udgør ≥ ${fmtPct(CURRENT_MODEL.minOrsWeightCoverage)} af vægten.`);
p('- Score og datakvalitet holdes adskilt. Datakvalitet er ikke statistisk sikkerhed.');
p('- Koncernscoren beregnes på det samlede datagrundlag, ikke som gennemsnit af enhedsscorer. Successionsmatching sker på tværs af hele organisationen.');
p('- Samme efterfølger dækker højst ét behov. Risici med samme rod tælles én gang i overblikket.');
p(`- Scorer vises som heltal; ændringer under ${CURRENT_MODEL.changeResolution} point vises som uændrede.`);
p('- Individuel afgangssandsynlighed udledes aldrig. Afgang simuleres kun som eksplicit antagelse.');
p();
p('## 3. ORS-formlen');
p();
p('```');
p('vægtet gennemsnit = Σ(vægt_d × score_d) / Σ vægt_d        (kun dimensioner med score)');
p(`ORS               = min(vægtet gennemsnit; svageste dimension + ${CURRENT_MODEL.weaknessCapPoints})`);
p('```');
p();
p('| Dimension | Vægt | Begrundelse |');
p('|---|---:|---|');
for (const d of D) p(`| ${d} ${DIMENSIONS[d].name} | ${fmtPct(CURRENT_MODEL.dimensionWeights[d])} | ${DIMENSIONS[d].weightRationale} |`);
p();
p('Statusgrænser (scoren afrundes før klassifikation):');
p();
p(`| Status | Grænse |`);
p('|---|---|');
p(`| Robust | ≥ ${CURRENT_MODEL.thresholds.robust} |`);
p(`| Tilstrækkelig | ${CURRENT_MODEL.thresholds.tilstrækkelig}–${CURRENT_MODEL.thresholds.robust - 1} |`);
p(`| Sårbar | ${CURRENT_MODEL.thresholds.sårbar}–${CURRENT_MODEL.thresholds.tilstrækkelig - 1} |`);
p(`| Kritisk | < ${CURRENT_MODEL.thresholds.sårbar} |`);
p(`| Utilstrækkeligt datagrundlag | dækningskrav ikke opfyldt |`);
p();
p('## 4. Dimensioner og indikatorer');
for (const d of D) {
  p();
  p(`### ${d} ${DIMENSIONS[d].name} (vægt ${fmtPct(CURRENT_MODEL.dimensionWeights[d])})`);
  p();
  p(`**Formål:** ${DIMENSIONS[d].purpose}`);
  p();
  p(`**Manglende data:** ${DIMENSIONS[d].missingData}`);
  for (const iid of DIMENSION_INDICATORS[d]) {
    const doc = INDICATORS[iid];
    p();
    p(`#### ${iid} ${doc.name} – ${fmtPct(CURRENT_MODEL.indicatorWeights[iid])} af dimensionen`);
    p();
    p(`- **Spørgsmål:** ${doc.question}`);
    p(`- **Formel:** \`${doc.formula}\``);
    p(`- **Input og enhed:** ${doc.unit}`);
    p(`- **Datakilder:** ${doc.sources.join('; ')}`);
    p(`- **Normalisering:** ${doc.normalization}`);
    p(`- **Manglende data:** ${doc.missing}${iid in MIN_N ? ` Minimum ${MIN_N[iid as keyof typeof MIN_N]} observationer.` : ''}`);
    p(`- **Vægt:** ${doc.weightRationale}`);
  }
}
p();
p('## 5. Parametre');
p();
p(`- Kritisk rolle: kritikalitet ≥ ${CRITICALITY.criticalRole}. Kritisk viden: ≥ ${CRITICALITY.knowledgeInScope} i D2, ≥ ${CRITICALITY.criticalKnowledge} kan udløse risici. Strategisk kapabilitet: fremtidig betydning ≥ ${CRITICALITY.strategicCapability}.`);
p(`- Dokumentation 0–3 → ${NORMALIZATION.documentation.join(' / ')}. Genetableringsfaktor ${NORMALIZATION.docRebuildFactor.join(' / ')}. Med ≥ 2 holdere: ${NORMALIZATION.rebuildWithBackupMonths} mdr.`);
p(`- Genetableringsscore lineær fra ${NORMALIZATION.rebuildBestMonths} mdr. (100) til ${NORMALIZATION.rebuildWorstMonths} mdr. (0).`);
p(`- Gablukning: ${fmtPct(NORMALIZATION.gapClosureFullScore)} lukning på 12 mdr. = 100. Milepælstolerance ${NORMALIZATION.milestoneToleranceDays} dage.`);
p(`- Tidsvinduer: evidens ${WINDOWS.evidenceMonths} mdr., progression ${WINDOWS.progressionMonths} mdr., onboarding ${WINDOWS.onboardingMonths} mdr., mobilitet ${WINDOWS.mobilityMonths} mdr.`);
p(`- Aktualitet: kapacitet og gennemførelse ≤ ${NORMALIZATION.capacityMaxAgeMonths} mdr.; successionsreview ≤ ${WINDOWS.planReviewMaxAgeMonths} mdr.; dokumentationsvurdering ≤ ${WINDOWS.docAssessmentMaxAgeMonths} mdr.`);
p();
p('## 6. Succession');
p();
p('- **Klar nu:** kan overtage nu med normal introduktion. **1–2 år:** forventes klar med planlagt udvikling. **3–5 år:** tæller ikke som dækning.');
p('- **Dokumenteret evidens:** vurderingen henviser til registrerede udviklingsforløb, uddelegeret ansvar, leverancer eller certificeringer. **Menneskelig vurdering:** skøn uden registreret evidens.');
p('- **Effektiv dækning:** prioriteret bipartit matching (Kuhns algoritme). Prioritet: kritikalitet, derefter højeste fremtidige betydning, derefter tidligste strategiske frist, derefter rolle-id. En dækket rolle mister aldrig dækning til en lavere prioriteret. Hver kandidat dækker højst ét behov.');
p('- **Ubesat lederrolle** tæller som 0 i I4.1.');
p('- **Tabt viden** (ingen kvalificerede holdere) giver genetableringsscore 0.');
p();
p('## 7. Risikomodel');
p();
p('```');
p('prioritet = 100 × K × E × (6 − B) / 125');
p('```');
p();
p('| Kategori | K (konsekvens) | E (eksponering) | B (beredskab, start 1, maks. 5) |');
p('|---|---|---|---|');
p('| Successionsgab | (kritikalitet + højeste fremtidige betydning) / 2; uden vurdering: kritikalitet | ubesat/ingen kandidater 5; kun 3–5 år eller ingen plan 4; dobbeltbooket 3; intet nødberedskab (klar inden for 2 år, ingen klar nu) 2 | +1 kandidat klar nu; +1 viden dokumenteret; +1 viden delt; +1 kandidat i dokumenteret udvikling |');
p('| Videnskoncentration | (kritikalitet + fremtidig betydning) / 2; uden vurdering: kritikalitet | én holder: basistid ≥ 12 mdr. 5, 6–11 4, < 6 3; ingen holdere 5 | + dokumentationsniveau (0–3; ikke vurderet giver intet tillæg); +1 person under oplæring |');
p('| Kapacitetsgab | fremtidig betydning | dækning < 50 % 5; < 65 % 4; < 80 % 3 | +1 pr. person i omstilling/udvikling (maks. 2); +1 ved ≥ 25 % lukning på 12 mdr. |');
p('| Kulturbærer | betydning − 1 | én bærer 4; ingen 5 | +1 beskrevet; +1 formel ejer; +1 gennemført ≥ 80 % |');
p();
p(`Bånd: kritisk ≥ ${RISK_MODEL.bands.kritisk}, høj ≥ ${RISK_MODEL.bands.høj}, moderat ≥ ${RISK_MODEL.bands.moderat}, ellers lav. Vurderet sandsynlighed vises separat og indgår ikke i prioriteten.`);
p();
p('## 8. Gennemregnede eksempler');
p();
p('### Eksempel A – kontrolleret testdatasæt (src/model/testutil.ts, verificeret i src/model/model.test.ts)');
p();
p('| Trin | Beregning |');
p('|---|---|');
p('| D1 | I1.1 = (5 × 70 + 3 × 100) / 8 = 81,25; I1.2 = 100; D1 = 0,65 × 81,25 + 0,35 × 100 = 87,81 |');
p('| D2 | I2.1 = 240/9 = 26,67; I2.2 = 575/9 = 63,89; I2.3 = 643,75/9 = 71,53; D2 = 49,05 |');
p('| D3 | Kandidat PX er nævnt til både RA (krit. 5) og RB (krit. 4) og tildeles RA. I3.1 = 500/9 = 55,56; I3.2 = 400/9 = 44,44; dækning 9/13. D3 = 51,11 |');
p('| D4 | Ingen dokumenteret udvikling = 0 (I4.4 udeladt: 2 < 3 observationer) |');
p('| D5 | Dækning 25 % < 60 % → utilstrækkeligt datagrundlag, udeladt |');
p('| D6 | I6.1 = 100 (gab 6 → 3); I6.2 = 50; I6.3 ikke relevant; D6 = (0,40 × 100 + 0,35 × 50) / 0,75 = 76,67 |');
p('| ORS | Vægtet gennemsnit = 54,55; loft = 0 + 30 = 30; **ORS = 30** (kritisk). Model 1.0 (uden loft): 54,55 |');
p();
p(`### Eksempel B – demonstrationsdata pr. ${asOf.split('-').reverse().join('.')}, hele organisationen`);
p();
p('| Dimension | Score | Datadækning |');
p('|---|---:|---:|');
for (const d of ors.dimensions) p(`| ${d.id} ${DIMENSIONS[d.id].name} | ${d.score === null ? '—' : fmtNumber(d.score, 1)} | ${fmtPct(d.coverage)} |`);
p();
p(`Vægtet gennemsnit ${fmtNumber(ors.weightedMean ?? 0, 1)}; loft ${fmtNumber(ors.cap ?? 0, 1)}; **ORS ${fmtNumber(ors.score ?? 0, 1)} → vises som ${Math.round(ors.score ?? 0)}**.`);
p();
p('De tre højest prioriterede risici med forskellig rod:');
p();
for (const r of top) p(`- ${r.id} ${r.title}: 100 × ${r.consequence.value} × ${r.exposure.value} × (6 − ${r.readiness.value}) / 125 = **${r.priority}**`);
p();
p('## 9. Antagelser og begrænsninger');
p();
p('- Vægte, tærskler og normaliseringer er ikke empirisk kalibrerede.');
p('- Mange input er menneskelige vurderinger; kvaliteten afhænger af ensartede vurderingsprocesser.');
p('- Kapacitet måles i årsværk; kompetenceniveau inden for årsværkene indgår ikke.');
p('- Kultur måles kun som praksis og infrastruktur – ikke holdninger, trivsel eller tillid.');
p('- Scoren viser sårbarhed, ikke årsagssammenhænge.');
p('- Flere indikatorer er andele; når en person uden registreret udvikling forlader kandidatpuljen, kan en andel stige uden reel forbedring.');
p();

writeFileSync(resolve(process.cwd(), 'docs/MODELKATALOG.md'), L.join('\n'));
console.log('docs/MODELKATALOG.md skrevet');
